// ============================================================
// Multi-IaC Generator Engine
// Supports Terraform, OpenTofu, Bicep, ARM Template Generation
// ============================================================

class IaCEngine {
  /**
   * Generate IaC template for an application specification
   * @param {string} format — 'terraform' | 'opentofu' | 'bicep' | 'arm'
   * @param {object} appSpec
   */
  generateTemplate(format = 'terraform', appSpec = {}) {
    const name = appSpec.name || 'cloudops-app';
    const location = appSpec.location || 'eastus';
    const cpu = appSpec.cpu || 1.0;
    const memory = appSpec.memory || '2Gi';

    switch (format.toLowerCase()) {
      case 'terraform':
      case 'opentofu':
        return this.generateTerraform(name, location, cpu, memory);
      case 'bicep':
        return this.generateBicep(name, location, cpu, memory);
      case 'arm':
        return this.generateARM(name, location, cpu, memory);
      default:
        throw new Error(`Unsupported IaC format: ${format}`);
    }
  }

  generateTerraform(name, location, cpu, memory) {
    return `
# Multi-Cloud Terraform / OpenTofu Specification
# Generated by AzureOps Enterprise IaC Engine

provider "azurerm" {
  features {}
}

resource "azurerm_resource_group" "rg" {
  name     = "rg-\${var.app_name}"
  location = "${location}"
}

resource "azurerm_container_app_environment" "env" {
  name                = "cae-\${var.app_name}"
  location            = azurerm_resource_group.rg.location
  resource_group_name = azurerm_resource_group.rg.name
}

resource "azurerm_container_app" "app" {
  name                         = "${name}"
  container_app_environment_id = azurerm_container_app_environment.env.id
  resource_group_name          = azurerm_resource_group.rg.name
  revision_mode                = "Single"

  template {
    container {
      name   = "${name}-container"
      image  = "\${var.container_image}"
      cpu    = ${cpu}
      memory = "${memory}"
    }
  }
}
`.trim();
  }

  generateBicep(name, location, cpu, memory) {
    return `
// Azure Bicep Template
// Generated by AzureOps Enterprise IaC Engine

param appName string = '${name}'
param location string = '${location}'
param containerImage string = 'mcr.microsoft.com/azuredocs/aci-helloworld:latest'

resource rg 'Microsoft.Resources/resourceGroups@2021-04-01' = {
  name: 'rg-\${appName}'
  location: location
}

resource containerApp 'Microsoft.App/containerApps@2022-03-01' = {
  name: appName
  location: location
  properties: {
    configuration: {
      ingress: {
        external: true
        targetPort: 80
      }
    }
    template: {
      containers: [
        {
          name: appName
          image: containerImage
          resources: {
            cpu: json('${cpu}')
            memory: '${memory}'
          }
        }
      ]
    }
  }
}
`.trim();
  }

  generateARM(name, location, cpu, memory) {
    return JSON.stringify({
      "$schema": "https://schema.management.azure.com/schemas/2019-04-01/deploymentTemplate.json#",
      "contentVersion": "1.0.0.0",
      "resources": [
        {
          "type": "Microsoft.App/containerApps",
          "apiVersion": "2022-03-01",
          "name": name,
          "location": location,
          "properties": {
            "template": {
              "containers": [
                {
                  "name": name,
                  "image": "mcr.microsoft.com/azuredocs/aci-helloworld:latest",
                  "resources": {
                    "cpu": cpu,
                    "memory": memory
                  }
                }
              ]
            }
          }
        }
      ]
    }, null, 2);
  }
}

module.exports = new IaCEngine();
